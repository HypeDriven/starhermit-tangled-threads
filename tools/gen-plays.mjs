// Writes the native play scripts (tests/native/*.play) from the content's
// own solutions (src/content.js generateLevel(...).solution), simulated with
// the real rules so every press is legal and the expected texts are exact:
// boards solved by the keyboard cursor (arrows + Enter, R), by finger on the
// board mirror's cells (named as ui.js named them), a Challenge lost to its
// move limit, Practice with undo and a hint on a short landscape phone, and
// the menus. Run `npm run plays` after content or label changes.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { generateLevel } from '../src/content.js';
import { createGame, applyAction, scoreState } from '../src/rules.js';
import { STRINGS } from '../src/strings.js';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'native');
const EN = STRINGS['en-US'];
const t = (k, v = {}) => EN[k].replace(/\{(\w+)\}/g, (m, x) => (v[x] != null ? String(v[x]) : m));

/** ui.js renderDomBoard's aria-label of a cell in a state. */
export function cellLabel(state, cell) {
  const info = new Map();
  state.strands.forEach((s, i) => {
    s.path.forEach((c, k) => info.set(c, { strand: i, tip: k === s.path.length - 1, anchor: k === 0, done: s.done }));
    if (!s.done) info.set(s.spool, { ...(info.get(s.spool) || {}), spool: i });
  });
  const r = Math.floor(cell / state.cols), c = cell % state.cols;
  const where = t('cellWhere', { row: r + 1, col: c + 1 });
  const inf = info.get(cell);
  if (inf && inf.strand !== undefined) {
    const part = t(inf.tip ? 'partTip' : inf.anchor ? 'partAnchor' : 'partBody');
    const flags = (inf.done ? t('cellReeled') : '') + (inf.spool !== undefined ? t('cellOnSpool') : '');
    return t('cellStrand', { n: inf.strand + 1, part, flags, where });
  }
  if (inf && inf.spool !== undefined) return t('cellEmptySpool', { n: inf.spool + 1, where });
  return t('cellEmpty', { where });
}

/** Solves a level with the keyboard cursor: lines, and the final state. */
function solveKeys(level, lines) {
  let state = createGame(level);
  let cursor = level.strands[0].anchor;
  const go = (cell) => {
    const dc = (cell % level.cols) - (cursor % level.cols), dr = Math.floor(cell / level.cols) - Math.floor(cursor / level.cols);
    for (let i = 0; i < Math.abs(dc); i++) lines.push(`key ${dc > 0 ? 'ArrowRight' : 'ArrowLeft'} 1`, 'frames 2');
    for (let i = 0; i < Math.abs(dr); i++) lines.push(`key ${dr > 0 ? 'ArrowDown' : 'ArrowUp'} 1`, 'frames 2');
    cursor = cell;
  };
  level.solution.forEach((sol, i) => {
    go(sol[0]);
    lines.push(`# strand ${i + 1}: select`, 'key Enter 1', 'frames 3');
    for (let k = 1; k < sol.length; k++) {
      go(sol[k]);
      lines.push('key Enter 1', 'frames 3');
      state = applyAction(state, { type: 'extend', strand: i, cell: sol[k] });
    }
    lines.push('key KeyR 1', 'frames 5');
    state = applyAction(state, { type: 'reel', strand: i });
  });
  return state;
}
/** Solves a level by finger on the board mirror's cells (select the anchor, each cell, the spool again to reel). */
function solveTouch(level, lines) {
  let state = createGame(level);
  level.solution.forEach((sol, i) => {
    lines.push(`# strand ${i + 1}`, `touch =${cellLabel(state, sol[0])}`, 'frames 6');
    for (let k = 1; k < sol.length; k++) {
      lines.push(`touch =${cellLabel(state, sol[k])}`, 'frames 6');
      state = applyAction(state, { type: 'extend', strand: i, cell: sol[k] });
    }
    lines.push(`touch =${cellLabel(state, sol[sol.length - 1])}`, 'frames 8');
    state = applyAction(state, { type: 'reel', strand: i });
  });
  return state;
}
function resultsLines(state, lines, level) {
  const sc = scoreState(state);
  lines.push('until 300 Total', 'frames 10', `expect ${state.terminal.reason === 'complete' ? t('boardComplete') : t('outOfMoves')}`,
    `expect ${t('resultsSub', { name: '', moves: state.moves, par: level.par, hints: state.hints, secs: '' }).split(' · ').slice(1, 3).join(' · ')}`,
    `expect =${sc.total}`);
}
const header = (desc, vp) => [`# Generated by tools/gen-plays.mjs: ${desc}`, `# viewport ${vp}`];
const main = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
function write(name, lines) { if (main) writeFileSync(join(out, name), lines.join('\n') + '\n'); }

// --- Journey stages 1-2 by keys on a desktop, Next between them
{
  const L = header('Journey stages 1 and 2 solved with the keyboard cursor on a desktop (Next between them), then Home.', '1280x800@1');
  L.push('until 600 =Play', 'frames 30', 'click =Play', 'until 300 Choose a mode', 'frames 10', 'click Journey.', 'frames 10', 'click Stage 1,', 'until 300 Reeled 0/', 'frames 30');
  const s1 = generateLevel('stage-1');
  L.push(`expect Moves 0 (par ${s1.par})`);
  resultsLines(solveKeys(s1, L), L, s1);
  L.push('save journey-results', 'click =Next', 'until 300 Stage 2', 'frames 30');
  const s2 = generateLevel('stage-2');
  L.push(`expect Moves 0 (par ${s2.par})`);
  resultsLines(solveKeys(s2, L), L, s2);
  L.push('click =Home', 'until 300 Journey progress: 2/40');
  write('journey-keys.play', L);
}
// --- Learn on a DPR-3 phone by finger on the board mirror
{
  const L = header('the Learn board (First Stitches) by finger on the board mirror on a DPR-3 phone, the lesson steps checked.', '390x844@3');
  const lv = generateLevel('tutorial');
  L.push('until 600 =Play', 'frames 30', 'touch =Play', 'until 300 Choose a mode', 'frames 10', 'touch Learn.', 'frames 10', 'touch =Start', 'until 300 Lesson 1/5', 'frames 30');
  let state = createGame(lv);
  const steps = [];
  lv.solution.forEach((sol, i) => {
    steps.push(`# strand ${i + 1}`, `touch =${cellLabel(state, sol[0])}`, 'frames 6');
    if (i === 0) steps.push('expect Lesson 2/5');
    for (let k = 1; k < sol.length; k++) {
      steps.push(`touch =${cellLabel(state, sol[k])}`, 'frames 6');
      state = applyAction(state, { type: 'extend', strand: i, cell: sol[k] });
      if (i === 0 && k === 1 && sol.length > 2) steps.push('expect Lesson 3/5');
    }
    if (i === 0) steps.push('expect Lesson 4/5', 'save learn-at-spool');
    steps.push(`touch =${cellLabel(state, sol[sol.length - 1])}`, 'frames 8');
    state = applyAction(state, { type: 'reel', strand: i });
    if (i === 0) steps.push('expect Lesson 5/5');
  });
  L.push(...steps);
  resultsLines(state, L, lv);
  L.push('save learn-results', 'touch =Home', 'until 300 =Play');
  write('learn-phone.play', L);
}
// --- a Challenge lost to its move limit (extend / pull back on one strand)
{
  const L = header('Challenge 1 lost to its move limit: one strand extended and pulled back by the cursor until the limit.', '1280x800@1');
  const lv = generateLevel('challenge-1');
  L.push('until 600 =Play', 'frames 30', 'click =Play', 'until 300 Choose a mode', 'frames 10', 'click Challenge.', 'frames 10', 'click Challenge 1,', 'until 300 Reeled 0/', 'frames 30',
    `expect Moves 0/${lv.moveLimit}`);
  const sol = lv.solution[0];
  L.push('# select strand 1 (the cursor starts on its anchor)', 'key Enter 1', 'frames 3');
  // the neighbour the solution takes, then back onto the anchor (the cell behind the tip)
  const dc = (sol[1] % lv.cols) - (sol[0] % lv.cols), dr = Math.floor(sol[1] / lv.cols) - Math.floor(sol[0] / lv.cols);
  const fwd = dc > 0 ? 'ArrowRight' : dc < 0 ? 'ArrowLeft' : dr > 0 ? 'ArrowDown' : 'ArrowUp';
  const back = { ArrowRight: 'ArrowLeft', ArrowLeft: 'ArrowRight', ArrowDown: 'ArrowUp', ArrowUp: 'ArrowDown' }[fwd];
  for (let m = 0; m < lv.moveLimit; m++) {
    L.push(`key ${fwd} 1`, 'frames 2', 'key Enter 1', 'frames 3');
    if (m < lv.moveLimit - 1) L.push(`key ${back} 1`, 'frames 2', 'key Enter 1', 'frames 3');
  }
  L.push('until 300 Total', 'frames 10', `expect ${t('outOfMoves')}`, 'save challenge-lost', 'click =Retry', 'until 300 Reeled 0/', `expect Moves 0/${lv.moveLimit}`,
    'key Escape 1', 'until 300 =Leave round', 'frames 10', 'click =Leave round', 'until 300 =Play');
  write('challenge-limit.play', L);
}
// --- Practice (easy) on a short landscape phone: a wrong turn undone, a hint, solved by finger
{
  const L = header('Practice (easy) on a short landscape phone: a wrong first move undone with U, a hint shown, the pause panel (colour-vision palette on and off), then solved by finger on the mirror.', '844x390@3');
  const lv = generateLevel('practice-easy');
  L.push('until 600 =Play', 'frames 30', 'touch =Play', 'until 300 Choose a mode', 'frames 10', 'touch Practice.', 'frames 10', 'touch Practice (easy),', 'until 300 Reeled 0/', 'frames 30');
  let state = createGame(lv);
  L.push('key KeyH 1', 'frames 5', `expect Hint: extend the red strand`);
  L.push('key KeyU 1', 'frames 5', `expect ${t('errNothingToUndo')}`);
  // a legal wrong move: the first strand to a free neighbour off its solution, then undo
  const sol = lv.solution[0];
  const occupied = new Set(lv.strands.flatMap((s) => [s.anchor, s.spool]));
  const nb = [sol[0] - lv.cols, sol[0] + lv.cols, sol[0] - 1, sol[0] + 1].filter((c) => c >= 0 && c < lv.cols * lv.rows && c !== sol[1] && !occupied.has(c)
    && (Math.abs((c % lv.cols) - (sol[0] % lv.cols)) + Math.abs(Math.floor(c / lv.cols) - Math.floor(sol[0] / lv.cols)) === 1));
  if (nb.length) {
    L.push(`touch =${cellLabel(state, sol[0])}`, 'frames 6', `touch =${cellLabel(state, nb[0])}`, 'frames 6', 'expect Moves 1', 'key KeyU 1', 'frames 6', 'expect Moves 0');
  }
  L.push('touch =Pause (Esc)', 'until 300 =Resume', 'frames 10', 'touch =Color-vision-safe palette #2', 'frames 10', 'save practice-pause', 'touch =Color-vision-safe palette #2', 'frames 10', 'touch =Resume', 'frames 20');
  state = solveTouch(lv, L);
  // session.js undo replays the log, so the hint (and invalid presses) before an undo are forgotten (the browser build's behaviour)
  state = { ...state, hints: nb.length ? 0 : 1 };
  state.terminal = { ...state.terminal, score: scoreState(state) };
  resultsLines(state, L, lv);
  write('practice-landscape.play', L);
}
